/**
 * Подсказка диспетчеру по отказу загрузки плана подвода.
 *
 * Лист плана верстают руками в РЖД, и раскладка плывёт день ото дня. Парсер к
 * этому приспособлен (ищет столбцы по содержимому), но подпись «План» осталась
 * единственной обязательной опорой — решение владельца 29.07.2026: парсер не
 * усложнять, а подписывать столбец в файле руками. Значит диспетчер должен
 * увидеть НЕ текст ошибки бэкенда, а что именно поправить в Excel.
 *
 * Распознаём по тексту ошибки: коды бэкенд не отдаёт, а вводить их ради подсказки
 * — трогать конвейер разбора, чего владелец просил не делать. Тексты живут в
 * internal/parser/plan/grid.go и internal/service/plan_sf_process.go; при их
 * правке поправить и совпадения здесь (неузнанная ошибка не теряется — она
 * показывается тостом как раньше).
 */
export interface PlanUploadHint {
  /** Заголовок окна — что случилось, одной строкой. */
  title: string;
  /** Что сделать. 2–4 коротких шага, по одному действию в каждом. */
  steps: string[];
  /** Необязательная приписка мелким шрифтом (проверка себя, важная оговорка). */
  note?: string;
}

/**
 * planUploadHint возвращает подсказку по сообщению об ошибке или null, если
 * случай неизвестен (тогда показываем обычный тост с текстом бэкенда).
 */
export function planUploadHint(message: string): PlanUploadHint | null {
  const m = (message ?? '').toLowerCase();

  // Не подписан столбец планового времени — единственная обязательная подпись.
  if (m.includes('строка шапки') && m.includes('план')) {
    return {
      title: 'В файле не подписан столбец «План»',
      steps: [
        'Открыть файл в Excel, перейти на лист сегодняшней даты.',
        'Найти столбец с временами вида 19:03, 21:12 — в нём есть строки, где кроме времени не заполнено ничего (свободные нитки). Обычно это F, G или H.',
        'В строке 2 (сразу под заголовком «План подвода поездов к станции …») вписать в этот столбец одно слово: План',
        'Сохранить файл и загрузить снова.',
      ],
      note: 'Регистр не важен («План», «план», «ПЛАН» — годится любой), но слово должно быть одно: без точки и без «План подвода». Проверка: справа обычно второе время (факт), за ним — число вагонов состава. Ничего не загрузилось, данные не изменились.',
    };
  }

  // Нашлись нитки, но состав у всех нулевой — уехал столбец итога поезда.
  if (m.includes('столбцы состава')) {
    return {
      title: 'В файле не распознан состав поездов',
      steps: [
        'Проверить, что перед первым терминалом есть столбец с общим числом вагонов поезда.',
        'Подписать его в строке 2 словом «Итого» или «Кол. ваг.».',
        'Сохранить файл и загрузить снова.',
      ],
      note: 'План с нулевым составом сознательно не принимается — иначе он лёг бы в базу пустым. Данные не изменились.',
    };
  }

  // Индексов поездов нет вовсе — обычно открыт не тот лист.
  if (m.includes('не найден столбец «индекс»') || m.includes('не найдено строк поездов')) {
    return {
      title: 'В файле нет строк поездов',
      steps: [
        'Проверить, что в книге открыт лист нужной даты.',
        'Убедиться, что в листе есть поезда с индексами вида 8600-793-9847.',
        'Если лист ещё не заполнен — дождаться готового файла.',
      ],
    };
  }

  // Файл другой станции либо выбрана не та вкладка.
  if (m.includes('а выбрана станция')) {
    return {
      title: 'Файл другой станции',
      steps: [
        'Переключиться на вкладку станции, чьей план загружаете.',
        'Либо взять файл выбранной станции.',
      ],
      note: message,
    };
  }

  // Стёрта первая строка — нельзя проверить принадлежность файла станции.
  if (m.includes('не найден заголовок')) {
    return {
      title: 'В файле стёрт заголовок',
      steps: [
        'Вернуть в первую строку листа заголовок «План подвода поездов к станции … на ДД.ММ.ГГГГ».',
        'Либо взять исходный файл.',
      ],
      note: 'Без заголовка нельзя проверить, той ли станции план, — файл отклонён.',
    };
  }

  // Не про файл: снимку вагонов не на что лечь.
  if (m.includes('дислокация устарела')) {
    return {
      title: 'Сначала обновите дислокацию',
      steps: [
        'На главной нажать «Обновить из АСУ» либо принять файлы ЛК.',
        'После обновления загрузить план заново.',
      ],
      note: 'Дело не в файле: снимок вагонов устарел, плану не на что лечь.',
    };
  }

  return null;
}
