/**
 * Имена станций и терминалов приходят из справочников ВЕРХНИМ регистром
 * («МЫС АСТАФЬЕВА») — так они заведены в реестре. Для заголовков и вкладок
 * показываем их человеческим написанием, не трогая сами данные.
 *
 * Слова короче 5 букв, стоящие не первыми, остаются как в реестре: «…ГЭС» —
 * аббревиатура, а не «Гэс». Дефис — разделитель слов («НАХОДКА-ВОСТОЧНАЯ»).
 */
export function stationTitle(name: string): string {
  return (name ?? '')
    .split(/(\s+|-)/)
    .map((w, i) => {
      if (/^\s+$|^-$/.test(w) || !w) return w;
      if (i > 0 && w.length <= 4 && w === w.toUpperCase()) return w; // аббревиатура: ГЭС, ВП
      return w.charAt(0).toUpperCase() + w.slice(1).toLowerCase();
    })
    .join('');
}
