// Схема приложения — dpport, и это инвариант кода (как московское время):
// имя зашито в SQL-миграции и смениться отдельно от них не может.
//
// Прод живёт за пулером соединений (PgBouncer), который отбивает search_path
// стартовым параметром DSN («unsupported startup parameter»), а выставить его
// на базе или роли там нельзя — админки к Postgres нет. Поэтому на search_path
// соединения не опираемся ВООБЩЕ: каждое обращение к таблице несёт схему явно —
// модели возвращают "dpport.<имя>" из TableName(), сырой SQL пишет dpport.<имя>
// прямо в тексте запроса, DDL подмены снимка — тоже (единственное исключение —
// цель ALTER TABLE ... RENAME TO: там имя без схемы, переименование схему не
// меняет). Сторож — TestRawSQLSchemaQualified в schema_guard_test.go.
