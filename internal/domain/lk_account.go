package domain

// LKAccount — учётка личного кабинета РЖД для автовыгрузки дислокации. Один
// поток (порт) = один аккаунт: у Аттис и НМТП кабинеты разные.
//
// Пароля здесь нет намеренно: его вводит диспетчер при запуске и он живёт
// только в памяти процесса (см. handler/lk_robot.go).
type LKAccount struct {
	OKPO  int64  // ОКПО грузополучателя; связь с ports.okpo
	Login string // логин в ЛК РЖД
	Name  string // подпись потока для модалки («Аттис», «НМТП»)
}
