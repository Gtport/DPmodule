-- ============================================================================
--  000060_ports_org_short — короткое имя организации для статус-панелей.
--
--  Карточка «Статус системы» показывает ветки дислокации по грузополучателям,
--  и подпись ветки зависела от источника: ЛК/робот писали в журнал терминалы
--  реестра («АЭ», «ГУТ-2·УТ-1»), а АСУ — код клиента провайдера («attis»/
--  «nmtp»). Решение владельца 10.08.2026: подпись всегда одна — короткое имя
--  организации (АТТИС / НМТП) независимо от источника.
--
--  Полное имя (ports.organisation, «ООО КОМПАНИЯ "АТТИС ЭНТЕРПРАЙС"») для
--  узкой карточки не годится, а сокращение из него не выводится — поэтому
--  отдельная колонка реестра, не хардкод. Новый грузополучатель = строка в
--  ports со своим org_short.
--
--  Идемпотентно (IF NOT EXISTS, сид только по пустому org_short), только
--  добавляющая. Сид адресуется по provider_client — устойчивому коду клиента,
--  а не по имени терминала.
-- ============================================================================

ALTER TABLE dpport.ports
    ADD COLUMN IF NOT EXISTS org_short text NOT NULL DEFAULT '';

COMMENT ON COLUMN dpport.ports.org_short
    IS 'Короткое имя организации для статус-панелей (АТТИС/НМТП); пусто — подпись по терминалам';

-- Сид значений (АТТИС/НМТП по provider_client) — клиентские данные, переехал в
-- scripts/clients/gtport.sql. Он же чинит давнюю дыру: seed_directories.sql
-- делает TRUNCATE ports и терял org_short — теперь клиентский сид, запускаемый
-- после пересева, возвращает значения.
