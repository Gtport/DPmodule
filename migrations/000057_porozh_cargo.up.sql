-- 000057: справочник кодов груза порожняковых рейсов (porozh_cargo).
--
--  Решение владельца 04.08.2026: изначально порожние вагоны, едущие в адрес
--  порта ПОД ПОГРУЗКУ, не должны получать статус 6 «порожний в пути» — они
--  живут обычным деревом статусов движения (2/4/5/9/10), чтобы подвод порожняка
--  был виден как у гружёных (прогноз, брошенные, кандидаты, прибытие).
--
--  Критерий «порожний под погрузку»: porozh_priznak = 1 И (вес 0/пуст ИЛИ код
--  груза из этого справочника). У реально опустевших по дороге (перегруз) и у
--  выгрузившихся в порту вес и код прежнего груза сохраняются (сверено с боевой
--  базой 04.08.2026: все 388 вагонов с признаком порожнего несли уголь ~70 т) —
--  они как получали 6/12, так и получают.
--
--  Коды — семейство ЕТСНГ 421 «Вагоны, перевозимые на своих осях» + 693157
--  (список владельца 04.08.2026, сверен с открытым справочником ЕТСНГ;
--  421049 добавлен для полноты семейства). Спорные коды выключаются галкой.

SET search_path TO dpport;

CREATE TABLE IF NOT EXISTS dpport.porozh_cargo (
    cargo_kod bigint  PRIMARY KEY,               -- код груза ЕТСНГ порожнякового рейса
    name      text    NOT NULL DEFAULT '',       -- наименование по ЕТСНГ (информационное)
    enabled   boolean NOT NULL DEFAULT true      -- участвует в критерии «под погрузку»
);

COMMENT ON COLUMN dpport.porozh_cargo.cargo_kod IS 'Код груза ЕТСНГ';
COMMENT ON COLUMN dpport.porozh_cargo.name      IS 'Наименование (по ЕТСНГ)';
COMMENT ON COLUMN dpport.porozh_cargo.enabled   IS 'Включён';

INSERT INTO dpport.list_tables (name, name_ru, editable) VALUES
    ('porozh_cargo', 'Коды груза порожняковых рейсов', true)
ON CONFLICT (name) DO NOTHING;

