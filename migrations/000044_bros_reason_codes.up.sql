-- ============================================================================
--  000044_bros_reason_codes — справочник официальных кодов бросания РЖД.
--
--  Классификатор причин отстановки поезда от движения («брошен», статус 5,
--  code_oper=92). code — двузначный код («01».."95"), description — расшифровка.
--  Наполнение — выгрузка из БД gtport (тот же классификатор). Расшифровки
--  правятся в Админе: справочник заведён в реестр list_tables.
--
--  Это первая ветка подсистемы «Брошенные». Снимок активных бросков (bros),
--  журнал (bros_journal), ручки active/history/journal и экраны — следующие
--  ветки; здесь только справочник кодов (чтение + админ-редактор).
--
--  Идемпотентно (CREATE TABLE IF NOT EXISTS, ON CONFLICT DO NOTHING),
--  только добавляющая.
-- ============================================================================

SET search_path TO dpport;

CREATE TABLE IF NOT EXISTS dpport.bros_reason_codes (
    code        varchar(10) PRIMARY KEY,   -- код классификатора РЖД (01..95)
    description text NOT NULL               -- расшифровка причины
);

-- Справочник — в админ-редактор (реестр list_tables, ключ code).
INSERT INTO dpport.list_tables (name, name_ru, editable) VALUES
    ('bros_reason_codes', 'Коды бросания (классификатор РЖД)', true)
ON CONFLICT (name) DO NOTHING;

COMMENT ON COLUMN dpport.bros_reason_codes.code        IS 'Код';
COMMENT ON COLUMN dpport.bros_reason_codes.description IS 'Причина бросания';

