-- ============================================================================
--  000062_history_not_arrived — пометка «недоехавший» на рейсе истории.
--
--  Решение владельца 14.08.2026: пропавшего из дислокации (запись-8) старший
--  оператор/админ может УДАЛИТЬ из кандидатов на прибытие. Рейс такого вагона
--  в vagon_history без прибытия выглядел бы вечно «в пути»: попадал в фильтр
--  «не выгруж.» и в отчёт по просрочке доставки. Пометка закрывает рейс явно:
--  вагон не доехал, и это решение человека, а не дыра данных.
--
--  Снимается автоматически, если вагон вернулся в дислокацию и рейс получил
--  реальный переход статуса (historyUpdateFields) — жизнь вернее пометки.
--
--  Идемпотентно (IF NOT EXISTS), только добавляющая.
-- ============================================================================

ALTER TABLE dpport.vagon_history
    ADD COLUMN IF NOT EXISTS not_arrived boolean NOT NULL DEFAULT false;

COMMENT ON COLUMN dpport.vagon_history.not_arrived
    IS 'Недоехавший: рейс закрыт вручную удалением из пропавших (вагон не прибыл); фильтр экрана истории, исключается из «не выгруж.» и отчёта просрочки';
