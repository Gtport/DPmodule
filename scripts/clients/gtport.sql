UNION ALL SELECT 'report_preset', count(*) FROM report_preset
UNION ALL SELECT 'max_route', count(*) FROM max_route
UNION ALL SELECT 'nmtp_mark', count(*) FROM nmtp_mark
UNION ALL SELECT 'nmtp_column', count(*) FROM nmtp_column
UNION ALL SELECT 'ports c org_short', count(*) FROM ports WHERE org_short <> '';
