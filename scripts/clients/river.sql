-- ============================================================================
--  scripts/clients/river.sql — клиентский сид ООО «АНБ» (речной порт, ст. АМУР).
--
--  Профиль клиента (из выгрузки ЛК за 31.07–12.08.2026, ~135 срезов):
--  нефтебаза на Амуре, один грузополучатель ОКПО 33576117, станция назначения
--  АМУР (970302, ДВС). Грузы — нефтепродукты в цистернах (дизтопливо 214043/
--  214039, авиатопливо 212052, бензин 211056; все — группа «НЕФТЬ И
--  НЕФТЕПРОДУКТЫ» словаря cargo). Подход ~430 вагонов за две недели.
--  Плана подвода у станции НЕТ: plan_profile не заполняется, Stage 4 считает
--  прогноз по перерабатывающей способности (ports.pc_*).
--
--  Запускать из корня репозитория, ПОСЛЕ migrate up и seed_directories.sql:
--      psql "$PG_DSN" -v ON_ERROR_STOP=1 -f scripts/clients/river.sql
--  Идемпотентно; прогонять после каждого пересева справочников.
-- ============================================================================

SET search_path TO dpport;

-- ── Имя клиента и пороги приёма ──────────────────────────────────────────────
--  Дислокация грузится РУКАМИ (робот ЛК выключен, своего аккаунта пока нет),
--  поэтому порог устаревания ослаблен до 12 часов: дефолтные 60 минут отвергали
--  бы выгрузку, снятую владельцем пару часов назад. Порог разрыва между
--  кабинетами не трогаем — кабинет один.
UPDATE dpport.client_settings
   SET client_name = 'АНБ (речной порт, ст. Амур)',
       ingest_policy = jsonb_set(ingest_policy,
           '{dislocation,max_staleness_minutes}', '720'),
       updated_at = now()
 WHERE id = 1 AND client_name IN ('', 'DPport');

-- Пороги Stage 4 (решение владельца 12.08.2026): отправки АНБ идут мелкими
-- партиями и одиночными вагонами — прогноз считается ВСЕМ группам, без
-- отсечки по размеру (у трёх терминалов было 20/10).
UPDATE dpport.client_settings
   SET extra = jsonb_set(COALESCE(extra, '{}'::jsonb), '{stage4}',
         '{"min_vagon_count":1,"min_vagon_bros":1,"bros_penalty_h":72}'::jsonb),
       updated_at = now()
 WHERE id = 1;

-- ── Портрет станции АМУР: бесплановая, с поправкой приёма ────────────────────
--  Плана подвода у станции нет (mode='capacity', plan_code пуст) — экран и меню
--  «План подвода» остаются скрытыми, в реестр парсера плана строка не идёт.
--  correction_coef=2 (решение владельца 14.08.2026): норматив выгрузки по
--  документам порта — 24 ваг/сут (ports.pc_other, port_cargo_line), а фактически
--  подают в 2–2,5 раза больше (замер по vagon_history 12–14.08: 41/43/90 вагонов
--  в сутки при 22 стоящих невыгруженными, очередь не растёт). Норматив остаётся
--  нормативом — он же в «Грузовой работе»; на очередь причала Stage 4 работает
--  pc × correction_coef. Ослабить обратно = поправить одно число здесь и в Админе.
--  slot_tolerance_h/max_train_length оставлены нулевыми: расписания ниток нет,
--  длину состава для АНБ владелец не задавал.
INSERT INTO dpport.plan_profile
    (station_code, station_name, mode, plan_code, correction_coef,
     match_requires_naznach, our_terminals, slot_tolerance_h, max_train_length)
VALUES ('970302', 'АМУР', 'capacity', '', 2.0, false, '["АНБ"]'::jsonb, 0, 0)
ON CONFLICT (station_code) DO UPDATE
   SET mode = EXCLUDED.mode,
       correction_coef = EXCLUDED.correction_coef,
       updated_at = now();

